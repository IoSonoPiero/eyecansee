/// What the server holds and saw.
pub struct Server {
    pub port: u16,
    pub password: String,
    /// A PNG in `/album/a.png`.
    pub png: Vec<u8>,
    /// Every command, the password as "PASS ok" or "PASS wrong".
    pub log: Mutex<Vec<String>>,
}

impl Server {
    pub fn logins(&self) -> Vec<String> {
        self.log.lock().unwrap().iter().filter(|l| l.starts_with("PASS")).cloned().collect()
    }
}

trait Stream: Read + Write + Send {}
impl<T: Read + Write + Send> Stream for T {}

fn tls_config() -> Arc<rustls::ServerConfig> {
    let provider = Arc::new(rustls::crypto::ring::default_provider());
    let key = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(KEY.to_vec()));
    let config = rustls::ServerConfig::builder_with_provider(provider)
        .with_safe_default_protocol_versions()
        .unwrap()
        .with_no_client_auth()
        .with_single_cert(vec![CertificateDer::from(CERT.to_vec())], key)
        .unwrap();
    Arc::new(config)
}

/// The TLS of the server side on `tcp`, the handshake done.
fn secured(tcp: TcpStream, config: &Arc<rustls::ServerConfig>) -> std::io::Result<rustls::StreamOwned<rustls::ServerConnection, TcpStream>> {
    let conn = rustls::ServerConnection::new(config.clone()).map_err(std::io::Error::other)?;
    let mut tls = rustls::StreamOwned::new(conn, tcp);
    while tls.conn.is_handshaking() {
        tls.conn.complete_io(&mut tls.sock)?;
    }
    Ok(tls)
}

/// One line of the client, without its "\r\n"; `None` at the end of the connection.
fn line(s: &mut dyn Stream) -> Option<String> {
    let mut bytes = Vec::new();
    let mut b = [0u8];
    loop {
        match s.read(&mut b) {
            Ok(1) if b[0] == b'\n' => return Some(String::from_utf8_lossy(&bytes).trim_end_matches('\r').to_string()),
            Ok(1) => bytes.push(b[0]),
            _ => return None,
        }
    }
}

/// `body` on the data connection of `listener`, in TLS, between "150" and "226".
fn send(s: &mut dyn Stream, listener: TcpListener, body: &[u8], config: &Arc<rustls::ServerConfig>) -> std::io::Result<()> {
    s.write_all(b"150 here it comes\r\n")?;
    let (tcp, _) = listener.accept()?;
    let mut data = secured(tcp, config)?;
    data.write_all(body)?;
    data.conn.send_close_notify();
    data.flush()?;
    drop(data);
    s.write_all(b"226 sent\r\n")
}

fn session(control: TcpStream, server: &Server, config: &Arc<rustls::ServerConfig>) -> std::io::Result<()> {
    let mut s: Box<dyn Stream> = Box::new(control.try_clone()?);
    s.write_all(b"220 test FTPS server\r\n")?;
    let mut data: Option<TcpListener> = None;
    while let Some(line) = line(s.as_mut()) {
        let (command, arg) = line.split_once(' ').unwrap_or((&line, ""));
        let command = command.to_ascii_uppercase();
        let logged = match command.as_str() {
            "PASS" if arg == server.password => "PASS ok".to_string(),
            "PASS" => "PASS wrong".to_string(),
            _ => line.clone(),
        };
        server.log.lock().unwrap().push(logged);
        let answer = match command.as_str() {
            "AUTH" => {
                s.write_all(b"234 TLS, please\r\n")?;
                // A client that refused the certificate leaves here.
                s = Box::new(secured(control.try_clone()?, config)?);
                continue;
            }
            "USER" => "331 password, please".to_string(),
            "PASS" if arg == server.password => "230 logged in".to_string(),
            "PASS" => "530 Login incorrect.".to_string(),
            "PBSZ" | "PROT" | "TYPE" | "NOOP" => "200 fine".to_string(),
            "PWD" => "257 \"/\" is the current folder".to_string(),
            "QUIT" => return s.write_all(b"221 bye\r\n"),
            "PASV" => {
                let listener = TcpListener::bind("127.0.0.1:0")?;
                let port = listener.local_addr()?.port();
                data = Some(listener);
                format!("227 Entering Passive Mode (127,0,0,1,{},{})", port >> 8, port & 255)
            }
            "CWD" => if matches!(arg.trim_end_matches('/'), "" | "/" | "/album") { "250 fine" } else { "550 no such folder" }.to_string(),
            "SIZE" if arg == "/album/a.png" => format!("213 {}", server.png.len()),
            "LIST" | "RETR" => {
                let body = match (command.as_str(), arg.trim_end_matches('/')) {
                    ("LIST", "" | "/") => Some(b"drwxr-xr-x    2 me       users        4096 Oct 30 09:10 album\r\n".to_vec()),
                    ("LIST", "/album") => Some(format!("-rw-r--r--    1 me       users {:>12} Oct 30 09:10 a.png\r\n", server.png.len()).into_bytes()),
                    ("RETR", "/album/a.png") => Some(server.png.clone()),
                    _ => None,
                };
                match (body, data.take()) {
                    (Some(body), Some(listener)) => {
                        send(s.as_mut(), listener, &body, config)?;
                        continue;
                    }
                    _ => "550 no such file or folder".to_string(),
                }
            }
            _ => "500 unknown command".to_string(),
        };
        s.write_all(format!("{answer}\r\n").as_bytes())?;
    }
    Ok(())
}

/// Starts the server on a free port of 127.0.0.1, with `password` for every user.
pub fn start(password: &str) -> Arc<Server> {
    let control = TcpListener::bind("127.0.0.1:0").unwrap();
    let mut png = Vec::new();
    image::DynamicImage::new_rgb8(8, 6).write_to(&mut std::io::Cursor::new(&mut png), image::ImageFormat::Png).unwrap();
    let server = Arc::new(Server { port: control.local_addr().unwrap().port(), password: password.to_string(), png, log: Mutex::new(Vec::new()) });
    let (shared, config) = (server.clone(), tls_config());
    std::thread::spawn(move || {
        for connection in control.incoming().flatten() {
            let (server, config) = (shared.clone(), config.clone());
            // A client that leaves in the middle (a refused certificate) ends its session, nothing more.
            std::thread::spawn(move || session(connection, &server, &config));
        }
    });
    server
}
